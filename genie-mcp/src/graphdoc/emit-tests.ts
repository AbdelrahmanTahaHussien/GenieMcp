import { graphdocMkdir as mkdir, graphdocRm as rm, graphdocWriteFile as writeFile } from "./write-guard.js";
import { dirname, join, relative } from "node:path";
import type { FileInfo, SpecFile } from "./types.js";
import {
  buildGraphData,
  computeDisplayNames,
  escapeMdCell,
  wikiLinkFor,
} from "./graph-core.js";
import { SPECS_DIRNAME, specNames } from "./spec-analyzer.js";

export const TESTS_FILENAME = "Tests.md";

/**
 * Tests.md — the tester's view of the graph (written only with includeSpecs):
 * coverage summary, units no spec touches, and every spec file with the units
 * it exercises and its test cases.
 */
export async function emitTests({
  cache,
  srcRoot,
  docsDir,
  repoRoot,
  specs,
}: {
  cache: Map<string, FileInfo>;
  srcRoot: string;
  docsDir: string;
  repoRoot: string;
  specs: SpecFile[];
}): Promise<void> {
  const { nodes } = buildGraphData(cache, srcRoot);
  const displayNames = computeDisplayNames(cache, srcRoot);
  const byDisplay = new Map(nodes.map((n) => [n.displayName, n]));
  const link = (file: string, name: string): string => {
    const d = displayNames.get(`${file}::${name}`) ?? name;
    const n = byDisplay.get(d);
    return n ? wikiLinkFor(n, srcRoot) : `[[${d}]]`;
  };
  const specLink = (file: string): string =>
    `[\`${relative(repoRoot, file)}\`](${relative(docsDir, file).replace(/\\/g, "/")})`;

  const names = specNames(specs, repoRoot);
  const covered = new Set(
    specs.flatMap((s) =>
      s.targets.map((t) => displayNames.get(`${t.file}::${t.name}`) ?? t.name),
    ),
  );
  const untested = nodes
    .filter((n) => !covered.has(n.displayName))
    .sort((a, b) => a.displayName.localeCompare(b.displayName));
  const testCount = specs.reduce((n, s) => n + s.tests.length, 0);
  const pct = nodes.length
    ? Math.round((100 * (nodes.length - untested.length)) / nodes.length)
    : 0;

  const lines: string[] = [];
  lines.push("# Tests");
  lines.push("");
  lines.push(
    "> Spec coverage map — which spec files exercise which units. Auto-generated by `graphdoc-mcp` (`includeSpecs: true`).",
  );
  lines.push(
    "> A unit counts as covered when a spec imports it directly; this is an import map, not line coverage.",
  );
  lines.push("");
  lines.push("| Spec files | Test cases | Units covered |");
  lines.push("|---|---|---|");
  lines.push(
    `| ${specs.length} | ${testCount} | ${nodes.length - untested.length} / ${nodes.length} (${pct}%) |`,
  );
  lines.push("");

  lines.push(`## Untested units (${untested.length})`);
  lines.push("");
  if (untested.length === 0) {
    lines.push("- *(every unit is imported by at least one spec)*");
  } else {
    lines.push("| Unit | Kind | Source |");
    lines.push("|---|---|---|");
    for (const n of untested)
      lines.push(
        `| ${wikiLinkFor(n, srcRoot)} | ${n.kind} | \`${escapeMdCell(relative(repoRoot, n.file))}\` |`,
      );
  }
  lines.push("");

  lines.push(`## Spec files (${specs.length})`);
  lines.push("");
  if (specs.length === 0) lines.push("- *(no spec files found)*");
  for (const s of specs) {
    lines.push(`### ${relative(repoRoot, s.file)}`);
    lines.push("");
    lines.push(
      `*Page: ${names.get(s.file)!.link} · Source: ${specLink(s.file)}*`,
    );
    lines.push("");
    const targets = [
      ...new Set(s.targets.map((t) => link(t.file, t.name))),
    ].sort();
    lines.push(
      `**Covers:** ${targets.length ? targets.join(", ") : "*(no units from the analyzed graph)*"}`,
    );
    if (s.outsideGraph.length)
      lines.push(
        "",
        `**Also imports (outside the analyzed graph):** ${s.outsideGraph
          .map((f) => `\`${relative(repoRoot, f)}\``)
          .join(", ")}`,
      );
    lines.push("");
    lines.push(`**Test cases (${s.tests.length}):**`);
    lines.push("");
    if (s.tests.length === 0)
      lines.push("- *(no describe/it/test titles found)*");
    for (const t of s.tests) lines.push(`- ${t}`);
    lines.push("");
  }

  await mkdir(docsDir, { recursive: true });
  await writeFile(join(docsDir, TESTS_FILENAME), lines.join("\n"));
  console.error(
    `wrote ${TESTS_FILENAME} (${specs.length} specs, ${testCount} tests, ${pct}% of units covered)`,
  );
}

/**
 * One page per spec under docs/specs/ (mirroring the repo layout), wiki-linked
 * to every unit it covers — so specs show up as connected nodes in Obsidian's
 * graph view. Fully regenerated each run (no curated content lives here).
 */
export async function emitSpecPages({
  cache,
  srcRoot,
  docsDir,
  repoRoot,
  specs,
}: {
  cache: Map<string, FileInfo>;
  srcRoot: string;
  docsDir: string;
  repoRoot: string;
  specs: SpecFile[];
}): Promise<void> {
  const specsDir = join(docsDir, SPECS_DIRNAME);
  await rm(specsDir, { recursive: true, force: true });

  const { nodes } = buildGraphData(cache, srcRoot);
  const displayNames = computeDisplayNames(cache, srcRoot);
  const byDisplay = new Map(nodes.map((n) => [n.displayName, n]));
  const names = specNames(specs, repoRoot);

  for (const s of specs) {
    const { name, page } = names.get(s.file)!;
    const pageFile = join(docsDir, page);
    const covers = [
      ...new Set(
        s.targets.map(
          (t) => displayNames.get(`${t.file}::${t.name}`) ?? t.name,
        ),
      ),
    ].sort();
    const link = (d: string) => {
      const n = byDisplay.get(d);
      return n ? wikiLinkFor(n, srcRoot) : `[[${d}]]`;
    };

    const lines: string[] = [];
    lines.push("---");
    lines.push("type: spec");
    lines.push("tags: [spec]");
    lines.push(`source: ${relative(repoRoot, s.file)}`);
    if (covers.length) {
      lines.push("covers:");
      for (const c of covers) lines.push(`  - ${c}`);
    } else lines.push("covers: []");
    lines.push("---");
    lines.push("");
    lines.push(`# 🧪 ${name}`);
    lines.push("");
    lines.push(
      `*Spec file [\`${relative(repoRoot, s.file)}\`](${relative(dirname(pageFile), s.file).replace(/\\/g, "/")}) · all specs: [[Tests]]*`,
    );
    lines.push("");
    lines.push("## Covers");
    lines.push("");
    if (!covers.length) lines.push("- *(no units from the analyzed graph)*");
    for (const c of covers) lines.push(`- ${link(c)}`);
    if (s.outsideGraph.length) {
      lines.push("");
      lines.push("**Also imports (outside the analyzed graph):**");
      for (const f of s.outsideGraph)
        lines.push(`- \`${relative(repoRoot, f)}\``);
    }
    lines.push("");
    lines.push(`## Test cases (${s.tests.length})`);
    lines.push("");
    if (!s.tests.length) lines.push("- *(no describe/it/test titles found)*");
    for (const t of s.tests) lines.push(`- ${t}`);
    lines.push("");

    await mkdir(dirname(pageFile), { recursive: true });
    await writeFile(pageFile, lines.join("\n"));
  }
  console.error(`wrote ${specs.length} spec pages to docs/${SPECS_DIRNAME}/`);
}
