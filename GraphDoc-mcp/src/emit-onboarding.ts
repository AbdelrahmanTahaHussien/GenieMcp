/**
 * emit-onboarding.ts
 *
 * Generates ONBOARDING.md — a token-efficient briefing document designed
 * for two audiences:
 *
 *   1. Human newcomers — a structured "start here" guide with architecture
 *      overview, key entry points, hotspot components, and conventions.
 *
 *   2. AI agents — a compact reference they can load ONCE at the start of
 *      a session to understand the codebase without reading source files.
 *      Token cost is minimized by design: no code, no full source paths,
 *      just structured facts an agent needs to navigate.
 *
 * The file is regeneration-safe: hand-written blocks inside
 * <!-- ONBOARD:START --> / <!-- ONBOARD:END --> are preserved.
 */

import { writeFile, mkdir, readFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join, relative } from "node:path";
import type { OnboardingContext } from "./types.js";
import { readState, getOnboardNote, setOnboardNote } from "./state-store.js";

/**
 * Where (if anywhere) the hand-written Architecture Notes block is persisted in
 * graphdoc.json, so it survives even when the ONBOARDING.md file is gitignored.
 * `stateDir` is the docs root holding graphdoc.json; `noteKey` is "" for the
 * project root or "module:<unitName>" for a module.
 */
export type OnboardPersist = { stateDir: string; noteKey: string };

const ONBOARD_START = "<!-- ONBOARD:START -->";
const ONBOARD_END = "<!-- ONBOARD:END -->";
const ONBOARD_PLACEHOLDER =
  "> _Add architecture notes, conventions, gotchas, or links here. This block is preserved on regeneration._";

async function readExistingBlock(docsDir: string): Promise<string | null> {
  const filePath = join(docsDir, "ONBOARDING.md");
  if (!existsSync(filePath)) return null;
  try {
    const content = await readFile(filePath, "utf8");
    const start = content.indexOf(ONBOARD_START);
    const end = content.indexOf(ONBOARD_END);
    if (start !== -1 && end !== -1 && end > start) {
      return content.slice(start + ONBOARD_START.length, end).trim() || null;
    }
  } catch {
    /* ignore */
  }
  return null;
}

export async function emitOnboarding(
  ctx: OnboardingContext,
  docsDir: string,
  persist?: OnboardPersist,
): Promise<void> {
  const {
    projectInfo,
    stats,
    topLevel,
    hotspots,
    documented,
    edgeCount,
    wikiLinks,
    specs,
  } = ctx;
  // Path-qualified link for colliding names, bare `[[Name]]` otherwise.
  const link = (displayName: string): string =>
    wikiLinks.get(displayName) ?? `[[${displayName}]]`;

  // graphdoc.json is the source of truth; fall back to the on-disk file's block
  // (so a fresh clone with notes only in JSON still restores them).
  const jsonNote = persist
    ? getOnboardNote(await readState(persist.stateDir), persist.noteKey)
    : undefined;
  const existingBlock = jsonNote ?? (await readExistingBlock(docsDir));
  const handwrittenBlock = existingBlock ?? ONBOARD_PLACEHOLDER;

  const kindEmoji: Record<string, string> = {
    component: "🧩",
    class: "🏛",
    function: "⚡",
    service: "🔧",
    module: "📦",
    other: "📄",
  };

  const lines: string[] = [];

  // ── header ────────────────────────────────────────────────────────────────
  lines.push(`# Onboarding Guide`);
  lines.push(``);
  lines.push(
    `> Auto-generated by \`graphdoc-mcp\`. Regenerate with \`analyze_project\`.`,
  );
  lines.push(
    `> Hand-written notes in the block below are preserved across regenerations.`,
  );
  lines.push(``);

  // ── project snapshot ──────────────────────────────────────────────────────
  lines.push(`## Project Snapshot`);
  lines.push(``);
  lines.push(`| Property | Value |`);
  lines.push(`|---|---|`);
  lines.push(`| **Framework** | ${stats.framework} |`);
  lines.push(`| **Language** | ${stats.language} |`);
  lines.push(
    `| **Source root** | \`${relative(projectInfo.repoRoot, projectInfo.srcRoot)}\` |`,
  );
  const roots = projectInfo.roots;
  if (roots?.length) {
    lines.push(
      `| **Entry point** | *(none — ${topLevel.length} independent roots)* |`,
    );
    lines.push(`| **Roots** | ${roots.map((r) => `\`${r}\``).join(", ")} |`);
  } else {
    lines.push(
      `| **Entry point** | \`${relative(projectInfo.repoRoot, projectInfo.rootFile)}\` |`,
    );
    lines.push(`| **Root unit** | \`${projectInfo.rootName}\` |`);
  }
  lines.push(`| **Files analyzed** | ${stats.files} |`);
  lines.push(
    `| **Units** | ${stats.units} (components / classes / functions) |`,
  );
  lines.push(`| **Edges** | ${edgeCount} (dependency relationships) |`);
  if (specs)
    lines.push(
      `| **Specs** | ${specs.files} files · ${specs.tests} test cases · ${specs.coveredUnits}/${specs.totalUnits} units covered — see [[Tests]] |`,
    );
  lines.push(``);

  // ── hand-written block ───────────────────────────────────────────────────
  lines.push(`## Architecture Notes`);
  lines.push(`*(Edit this section — it is preserved on regeneration.)*`);
  lines.push(``);
  lines.push(ONBOARD_START);
  lines.push(handwrittenBlock);
  lines.push(ONBOARD_END);
  lines.push(``);

  // ── entry points ──────────────────────────────────────────────────────────
  lines.push(`## Entry Points`);
  lines.push(``);
  if (roots?.length) {
    lines.push(
      `This project has no single entry point. Each of these is an independent root (from ${roots.map((r) => `\`${r}\``).join(", ")}) — start with the one you are working on:`,
    );
  } else {
    lines.push(
      `Start reading from \`${projectInfo.rootName}\` — it is the root of the dependency tree.`,
    );
    lines.push(`Its direct children are:`);
  }
  lines.push(``);
  for (const child of topLevel.sort()) {
    lines.push(`- ${link(child)}`);
  }
  lines.push(``);

  // ── hotspots ──────────────────────────────────────────────────────────────
  lines.push(`## High-Reuse Units (Hotspots)`);
  lines.push(``);
  lines.push(`These units are used by the most others. Understand them early.`);
  lines.push(``);
  lines.push(`| Unit | Kind | Used by |`);
  lines.push(`|---|---|---|`);
  for (const { displayName, kind, usedBy } of hotspots) {
    lines.push(
      `| ${link(displayName)} | ${kindEmoji[kind] ?? "📄"} ${kind} | ${usedBy} |`,
    );
  }
  lines.push(``);

  // ── documented units ─────────────────────────────────────────────────────
  if (documented.length > 0) {
    lines.push(`## Documented Units`);
    lines.push(``);
    lines.push(
      `These units have doc comments — good reading for understanding intent.`,
    );
    lines.push(``);
    for (const { displayName, description } of documented.slice(0, 20)) {
      // truncate long descriptions to keep the doc token-efficient
      const short =
        description.length > 120
          ? description.slice(0, 120) + "…"
          : description;
      lines.push(`- **${link(displayName)}** — ${short}`);
    }
    if (documented.length > 20) {
      lines.push(
        `- *(and ${documented.length - 20} more — see \`docs/src/\`)*`,
      );
    }
    lines.push(``);
  }

  // ── navigation index ──────────────────────────────────────────────────────
  lines.push(`## Documentation Index`);
  lines.push(``);
  lines.push(`| Document | What it contains |`);
  lines.push(`|---|---|`);
  lines.push(`| [[Tree]] | Component/unit tree mindmap (Mermaid) |`);
  lines.push(`| [[Graph]] | Full dependency DAG — each unit appears once |`);
  lines.push(
    `| [[Matrix]] | Parent×child dependency matrix + reuse leaderboard |`,
  );
  lines.push(
    `| [[Api]] | Class diagram of units that expose props/parameters |`,
  );
  if (specs)
    lines.push(
      `| [[Tests]] | Spec coverage map: untested units + test cases per spec |`,
    );
  lines.push(`| \`docs/src/\` | Per-unit wiki pages with uses/used-by links |`);
  lines.push(``);

  // ── AI agent instructions ─────────────────────────────────────────────────
  lines.push(`## Instructions for AI Agents`);
  lines.push(``);
  lines.push(
    `> **Load this file first.** It is your token-efficient map of the codebase.`,
  );
  lines.push(`> Use it to navigate before reading any source file.`);
  lines.push(``);
  lines.push(`Workflow:`);
  lines.push(
    `1. Read **ONBOARDING.md** (this file) to understand the architecture.`,
  );
  lines.push(
    `2. Use \`get_unit\` / \`get_graph\` tools to explore relationships.`,
  );
  lines.push(
    `3. Read \`docs/src/<UnitName>.md\` for a specific unit's API and links.`,
  );
  lines.push(
    `4. Only open source files when you need the actual implementation.`,
  );
  lines.push(``);
  lines.push(
    `This order minimizes token consumption while maximizing context quality.`,
  );

  await mkdir(docsDir, { recursive: true });
  await writeFile(join(docsDir, "ONBOARDING.md"), lines.join("\n"));
  // Persist the (possibly hand-written) notes block to graphdoc.json so it
  // survives even when ONBOARDING.md itself is gitignored / regenerated.
  if (persist)
    await setOnboardNote(persist.stateDir, persist.noteKey, handwrittenBlock);
  console.error(`wrote ONBOARDING.md (${lines.length} lines)`);
}
